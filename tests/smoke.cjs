const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base='http://127.0.0.1:8765/?e2e=1';
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try {
  const ctx=await browser.newContext({viewport:{width:1365,height:768},deviceScaleFactor:1});
  const page=await ctx.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')console.log('BROWSER ERROR:',m.text())});
  await page.goto(base,{waitUntil:'load',timeout:45000});
  await page.locator('#welcomeName').fill('ArenaTester');
  await page.locator('#deviceLaptop').click();
  await page.locator('#welcomeGo').click();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#fighterArt .champion-webgl').count(),1,'animated 3D lobby preview should initialize');
  await page.locator('#fighterNext').click();
  assert.equal(await page.locator('#fighterName').innerText(),'EMBER','next fighter arrow should change fighter');
  await page.locator('#fighterPrev').click();
  assert.equal(await page.locator('#fighterName').innerText(),'BOLT','previous fighter arrow should change fighter');
  await page.locator('#championUpgrade').click();
  assert.match(await page.locator('#popupTitle').innerText(),/BOLT/,'upgrade shortcut should open upgrade screen');
  await page.locator('#popupClose').click();
  await page.locator('#fightersBtn').click();
  await page.getByRole('button',{name:/FROST.*LV/}).click();
  assert.equal(await page.locator('#fighterName').innerText(),'FROST');
  await page.evaluate(()=>{localStorage.setItem('clashLegendsCoins','600');window.clashLobbyRefresh()});
  await page.locator('#shopBtn').click();
  await page.getByRole('button',{name:/UPGRADE FROST/}).click();
  await page.getByRole('button',{name:/UPGRADE · 60 COINS/}).click();
  assert.match(await page.locator('#popupTitle').innerText(),/POWER 2/);
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashFrostLevel'))),2);
  assert.match(await page.locator('#championPower').innerText(),/POWER 2/,'lobby champion power badge should update');
  await page.locator('#popupClose').click();
  await page.locator('#shopBtn').click();
  await page.getByRole('button',{name:/COSMETIC SKINS/}).click();
  await page.getByRole('button',{name:/GOLDEN/}).click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('clashSkinFROST')),'1','Golden skin should equip');
  assert.equal(await page.evaluate(()=>localStorage.getItem('clashSkinOwnedFROST1')),'yes','Golden skin should be owned after purchase');
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashLegendsCoins'))),240,'Golden skin should deduct the price once');
  await page.getByRole('button',{name:/GOLDEN/}).click();
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashLegendsCoins'))),240,'Equipping an owned skin must be free');
  assert.match(await page.locator('#fighterSubtitle').innerText(),/GOLDEN/,'skin should be visible in lobby');
  await page.locator('#popupClose').click();
  await page.locator('#modesBtn').click();
  await page.getByRole('button',{name:/ARENA:/}).click();
  await page.getByRole('button',{name:/ANCIENT RUINS/}).click();
  await page.getByRole('button',{name:/CRYSTAL GROVE/}).click();
  await page.getByRole('button',{name:/BACK TO MODES/}).click();
  await page.getByRole('button',{name:/TRAINING ARENA/}).click();
  assert.match(await page.locator('#modeTitle').innerText(),/TRAINING/);
  await page.locator('#start').click();
  assert.equal(await page.evaluate(()=>window.__clashTest.snapshot().selectedFighter),4);
  assert.equal(await page.evaluate(()=>window.__clashTest.snapshot().map),1,'Crystal Grove layout must load for offline training');
  await page.waitForTimeout(700);
  const loaded3d=await page.evaluate(()=>Boolean(window.THREE)&&document.querySelector('#threeView canvas')!==null);
  assert(loaded3d,'Three.js WebGL canvas did not initialize');
  const camera=await page.evaluate(()=>window.__clashTest.snapshot().camera);
  assert(camera && camera.y>950,'camera should use the higher three-quarter perspective');
  assert(camera.span>=500,'camera must show enough of the arena');
  await page.evaluate(()=>window.__clashTest.skipIntro());
  const bush=await page.evaluate(()=>window.__clashTest.bushProbe());
  assert(bush&&bush.hidden,'a fighter in bushes must be concealed from a distant opponent');
  assert.equal(bush.revealedClose,false,'nearby opponents should reveal someone in bushes');
  assert.equal(bush.revealedAfterShot,false,'shooting from bushes should reveal the shooter');
  await page.waitForTimeout(500);
  // Real desktop pointer input must spend ammo and create a directed projectile.
  const beforeShot=await page.evaluate(()=>window.__clashTest.snapshot());
  await page.mouse.move(980,370);
  await page.mouse.down();
  await page.mouse.up();
  const afterShot=await page.evaluate(()=>window.__clashTest.snapshot());
  assert.equal(afterShot.ammo,beforeShot.ammo-1,'mouse click should consume one ammo');
  assert(afterShot.lastPlayerShot&&afterShot.lastPlayerShot.vx>0,'shot should travel toward the cursor on the right');
  await page.screenshot({path:'arena-desktop.png'});
  await page.evaluate(()=>window.__clashTest.forceWin());
  await page.waitForSelector('.result-card',{timeout:12000});
  assert.match(await page.locator('.result-card').innerText(),/TROPHIES/);
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashFrostTrophies'))),0,'training must not give trophies');
  await page.locator('#again').click();
  await page.waitForSelector('#fightersBtn');
  await page.evaluate(()=>{localStorage.setItem('clashFrostTrophies','400');localStorage.setItem('clashLegendsTrophies','400');window.clashLobbyRefresh()});
  await page.locator('#modesBtn').click();
  await page.getByRole('button',{name:/SOLO SHOWDOWN/}).click();
  await page.locator('#start').click();
  await page.evaluate(()=>window.__clashTest.forceLose());
  await page.waitForSelector('.result-card',{timeout:10000});
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashFrostTrophies'))),394,'trophy loss should scale with brawler trophies');
  await page.locator('#again').click();
  await page.waitForSelector('#modesBtn');
  await page.locator('#modesBtn').click();
  await page.getByRole('button',{name:/DUO SHOWDOWN/}).click();
  await page.locator('#start').click();
  const duo=await page.evaluate(()=>window.__clashTest.snapshot());
  assert.equal(duo.mode,'duo','Duo mode must be selected');
  assert.equal(duo.friendly,1,'Duo mode must spawn one AI teammate');
  assert.equal(duo.alive,9,'Duo mode must spawn 9 bots total');
  await page.evaluate(()=>window.__clashTest.forceWin());
  await page.waitForSelector('.result-card',{timeout:10000});
  assert.equal(await page.evaluate(()=>Number(localStorage.getItem('clashFrostTrophies'))),405,'Duo victory must award trophy rewards');
  await page.locator('#again').click();
  await page.waitForSelector('#questsBtn');
  await page.locator('#questsBtn').click();
  const txt=await page.locator('#popupOptions').innerText();
  assert.match(txt,/PLAY 3 MATCHES/);assert.match(txt,/WIN A SHOWDOWN/);assert.match(txt,/DEFEAT 8 RIVALS/);
  await page.locator('#popupClose').click();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('clashMatchHistory')||'[]').length),3,'match history should contain the win and loss');
  await page.locator('#rankedBtn').click();
  assert.match(await page.locator('#popupOptions').innerText(),/BOT/);
  await page.getByRole('button',{name:/MATCH HISTORY/}).click();
  assert.match(await page.locator('#popupTitle').innerText(),/LAST MATCHES/);
  await page.getByRole('button',{name:/BACK/}).click();
  await page.locator('#popupClose').click();
  await page.locator('#friendsBtn').click();
  assert.match(await page.locator('#popupTitle').innerText(),/LOCAL|DEVICE/);
  await page.getByRole('button',{name:/ONLINE FRIEND REQUESTS/}).click();
  await page.waitForFunction(()=>document.querySelector('#popupTitle').textContent.includes('ONLINE FRIENDS'),{timeout:10000});
  assert.match(await page.locator('#popupOptions').innerText(),/SIGN IN/,'online friends should show account sign in');
  assert.match(await page.locator('#popupOptions').innerText(),/CREATE ACCOUNT/,'online friends should show account creation');
  await page.locator('#popupClose').click();
  await page.screenshot({path:'arena-lobby.png'});
  assert.deepEqual(errors,[],'uncaught JavaScript errors on desktop');
  console.log('PASS desktop: profile, all-fighter selection, shop, upgrade, modes, renderer, practice win, negative trophies, quests, ranked, friends');
  await ctx.close();
  const mobile=await browser.newContext({viewport:{width:844,height:390},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const p=await mobile.newPage(),mobileErrors=[];
  p.on('pageerror',e=>mobileErrors.push(e.message));
  await p.goto(base,{waitUntil:'load',timeout:45000});
  await p.locator('#welcomeName').fill('PhoneTester');
  await p.locator('#devicePhone').click();
  await p.locator('#welcomeGo').click();
  await p.locator('#start').click();
  await p.waitForTimeout(500);
  await p.evaluate(()=>{window.__clashTest.skipIntro()});
  const b=await p.locator('#fire').boundingBox();assert(b&&b.width>30,'touch attack control is hidden');
  const cdp=await mobile.newCDPSession(p),xx=b.x+b.width/2,yy=b.y+b.height/2;
  const before=await p.evaluate(()=>window.__clashTest.snapshot().ammo);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:xx,y:yy,id:1}]});
  await p.waitForTimeout(350);
  assert.equal(await p.evaluate(()=>window.__clashTest.snapshot().ammo),before,'touch hold should aim only');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await p.waitForTimeout(120);
  assert.equal(await p.evaluate(()=>window.__clashTest.snapshot().ammo),before-1,'touch release should fire once');
  await p.screenshot({path:'arena-mobile.png'});
  assert.deepEqual(mobileErrors,[],'uncaught JavaScript errors on mobile');
  console.log('PASS mobile landscape: profile, controls and hold/drag/release attack');
  await mobile.close();
 }finally{await browser.close()}
})().catch(err=>{console.error('FAIL',err);process.exit(1)});
